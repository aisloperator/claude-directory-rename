#!/usr/bin/env python3
"""
NOTE: This script was generated by AI Sloperator (https://www.aisloperator.com)
using Claude Fable 5 High.

claude_rename.py — Rename a project directory without losing Claude Code sessions.

Claude Code stores session transcripts under:

    ~/.claude/projects/<encoded-absolute-path>/*.jsonl

where the encoded name is the absolute path with every character that isn't
a letter, digit, or dash replaced by a dash. If you rename a project folder
with plain `mv`, those sessions are orphaned and `claude --resume` finds
nothing. This script performs the rename AND migrates the session storage:

    1. Locates the old encoded project folder in ~/.claude/projects
    2. Moves it (and any nested sub-project folders) to the new encoded name
    3. Rewrites path references (e.g. "cwd") inside the .jsonl transcripts
    4. Renames the actual project directory on disk
    5. Rolls the Claude context back if the final rename fails

Usage:
    python3 claude_rename.py /path/to/old-name /path/to/new-name
    python3 claude_rename.py old new --dry-run       # show what would happen
    python3 claude_rename.py old new --skip-fs-move  # dir already renamed;
                                                     # just migrate sessions
"""

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

DEFAULT_PROJECTS_DIR = Path.home() / ".claude" / "projects"


def encode_path(path: Path) -> str:
    """Replicate Claude Code's project-path encoding.

    Every character that isn't [A-Za-z0-9-] becomes '-'. Examples:
      /Users/you/code/my-app     -> -Users-you-code-my-app
      C:\\Users\\you\\my_project -> C--Users-you-my-project
    """
    return re.sub(r"[^A-Za-z0-9-]", "-", str(path))


def find_project_dirs(projects_dir: Path, encoded: str) -> list[Path]:
    """Return the encoded project dir plus any nested sub-project dirs.

    Claude Code can create separate entries for subdirectories of a project
    (e.g. after /add-dir or launching inside a subfolder), so we migrate
    every folder whose name is the encoding or starts with '<encoding>-'.
    """
    if not projects_dir.is_dir():
        return []
    hits = []
    for entry in sorted(projects_dir.iterdir()):
        if entry.is_dir() and (entry.name == encoded or entry.name.startswith(encoded + "-")):
            hits.append(entry)
    return hits


def rewrite_jsonl(file: Path, replacements: list[tuple[str, str]], dry_run: bool) -> int:
    """Replace old-path strings inside a transcript. Returns hit count."""
    try:
        text = file.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError) as exc:
        print(f"    ! skipping {file.name}: {exc}")
        return 0
    hits = 0
    for old, new in replacements:
        hits += text.count(old)
        text = text.replace(old, new)
    if hits and not dry_run:
        file.write_text(text, encoding="utf-8")
    return hits


def main() -> int:
    ap = argparse.ArgumentParser(description="Rename a project dir and migrate Claude Code sessions.")
    ap.add_argument("old_path", help="current project directory")
    ap.add_argument("new_path", help="desired new project directory")
    ap.add_argument("--dry-run", action="store_true", help="print actions without changing anything")
    ap.add_argument("--skip-fs-move", action="store_true",
                    help="don't touch the filesystem dir (use if you already renamed it)")
    ap.add_argument("--projects-dir", type=Path, default=DEFAULT_PROJECTS_DIR,
                    help=f"override Claude projects dir (default: {DEFAULT_PROJECTS_DIR})")
    args = ap.parse_args()
    projects_dir = args.projects_dir.expanduser()

    old_path = Path(args.old_path).expanduser().resolve()
    # Don't resolve() new_path against the filesystem if it doesn't exist yet;
    # just make it absolute relative to cwd.
    new_path = Path(args.new_path).expanduser()
    if not new_path.is_absolute():
        new_path = Path.cwd() / new_path

    # ---- sanity checks -----------------------------------------------------
    if args.skip_fs_move:
        if not new_path.is_dir():
            sys.exit(f"error: --skip-fs-move given but {new_path} does not exist")
    else:
        if not old_path.is_dir():
            sys.exit(f"error: {old_path} is not a directory")
        if new_path.exists():
            sys.exit(f"error: {new_path} already exists — refusing to overwrite")

    old_enc, new_enc = encode_path(old_path), encode_path(new_path)
    print(f"old path : {old_path}\nnew path : {new_path}")
    print(f"old slug : {old_enc}\nnew slug : {new_enc}\n")

    sources = find_project_dirs(projects_dir, old_enc)
    if not sources:
        print(f"No Claude session folders found for {old_path} under {projects_dir}.")
        print("Nothing to migrate — check the folder names there if you expected sessions:")
        if projects_dir.is_dir():
            for entry in sorted(projects_dir.iterdir()):
                print(f"  {entry.name}")
        if not args.skip_fs_move and not args.dry_run:
            answer = input("Rename the directory anyway? [y/N] ").strip().lower()
            if answer == "y":
                shutil.move(str(old_path), str(new_path))
                print(f"moved {old_path} -> {new_path}")
        return 0

    # ---- plan the context moves --------------------------------------------
    moves: list[tuple[Path, Path]] = []
    for src in sources:
        dst = projects_dir / (new_enc + src.name[len(old_enc):])
        if dst.exists() and any(dst.iterdir()):
            sys.exit(f"error: destination {dst} already exists and is not empty.\n"
                     f"Merge or remove it manually, then re-run.")
        moves.append((src, dst))

    # Both raw and JSON-escaped forms, so Windows backslash paths inside
    # JSON strings ("C:\\Users\\...") are rewritten correctly too.
    replacements = [(str(old_path), str(new_path))]
    esc_old, esc_new = json.dumps(str(old_path))[1:-1], json.dumps(str(new_path))[1:-1]
    if esc_old != str(old_path):
        replacements.append((esc_old, esc_new))

    prefix = "[dry-run] " if args.dry_run else ""
    done: list[tuple[Path, Path]] = []
    try:
        # 1) move Claude context first (so a crash mid-way is easy to spot)
        for src, dst in moves:
            n = sum(1 for f in src.rglob("*.jsonl"))
            print(f"{prefix}move context: {src.name} -> {dst.name}  ({n} transcript(s))")
            if not args.dry_run:
                shutil.move(str(src), str(dst))
                done.append((src, dst))

        # 2) rewrite path references inside transcripts
        for src, dst in moves:
            root = src if args.dry_run else dst
            for f in sorted(root.rglob("*.jsonl")):
                hits = rewrite_jsonl(f, replacements, args.dry_run)
                if hits:
                    print(f"{prefix}  rewrote {hits} path reference(s) in {f.name}")

        # 3) finally, rename the real directory
        if not args.skip_fs_move:
            print(f"{prefix}move directory: {old_path} -> {new_path}")
            if not args.dry_run:
                shutil.move(str(old_path), str(new_path))
    except Exception as exc:
        print(f"\nerror: {exc}\nrolling back Claude context moves...", file=sys.stderr)
        for src, dst in reversed(done):
            if dst.exists() and not src.exists():
                shutil.move(str(dst), str(src))
                print(f"  restored {src.name}", file=sys.stderr)
        return 1

    if args.dry_run:
        print("\nDry run complete — no changes made.")
    else:
        print(f"\nDone. Resume with:\n  cd {new_path}\n  claude --resume")
    return 0


if __name__ == "__main__":
    sys.exit(main())
